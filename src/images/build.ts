import { initWasm, Resvg } from "@resvg/resvg-wasm";
import wasm from "@resvg/resvg-wasm/index_bg.wasm" with { type: "file" };
import { randomUUID } from "node:crypto";
import { closeSync, constants, existsSync, fstatSync, ftruncateSync, lstatSync, mkdirSync, openSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { composeSvg, type Canvas } from "./compose";
import { expand, format, SOURCE_DIRECTORY, verbatim, type ImageOutput, type ImagesConfig, type ImageTarget } from "./config";
import { encodeIco, encodePng, fromPremultiplied, type Pixels } from "./png";
import { parseSvg, type SvgSource } from "./svg";

let ready: Promise<void> | undefined;

async function rasterize(svg: string, width: number, height: number, opaque: boolean): Promise<Pixels> {
  await (ready ??= initWasm(readFileSync(wasm)));
  // No system fonts: sources may not contain text, so nothing depends on the machine.
  const renderer = new Resvg(svg, { fitTo: { mode: "original" }, font: { loadSystemFonts: false } });
  const image = renderer.render();
  try {
    if (image.width !== width || image.height !== height) throw new Error(`Rendered ${image.width}x${image.height} instead of ${width}x${height}.`);
    return fromPremultiplied(width, height, image.pixels, opaque);
  } finally { image.free(); renderer.free(); }
}

class Sources {
  private readonly loaded = new Map<string, { text: string; svg?: SvgSource }>();
  constructor(private readonly root: string) {}
  private entry(name: string) {
    let entry = this.loaded.get(name);
    if (!entry) {
      const file = path.join(this.root, SOURCE_DIRECTORY, `${name}.svg`);
      if (!existsSync(file)) throw new Error(`Image source '${name}' does not exist at ${SOURCE_DIRECTORY}/${name}.svg.`);
      entry = { text: readFileSync(file, "utf8") };
      this.loaded.set(name, entry);
    }
    return entry;
  }
  text(name: string): string { return this.entry(name).text; }
  parsed(names: Iterable<string>): Map<string, SvgSource> {
    return new Map([...names].map(name => { const entry = this.entry(name); return [name, entry.svg ??= parseSvg(name, entry.text)]; }));
  }
}

function layerSources(output: Pick<ImageOutput, "layers">): string[] {
  return output.layers.flatMap(layer => "source" in layer ? [layer.source] : []);
}

async function render(output: ImageOutput, canvas: Canvas, sources: Sources): Promise<Uint8Array | string> {
  const kind = format(output.path);
  if (kind === "xml") {
    let colors = "";
    for (const [name, color] of Object.entries(output.colors!)) {
      let hex = typeof color === "string" ? color : "";
      if (typeof color !== "string") {
        // The source's mean color over white, on a canvas of its own proportions, for settings that take a color.
        const parsed = sources.parsed([color.average]), [, , viewWidth, viewHeight] = parsed.get(color.average)!.viewBox;
        const width = Math.max(1, Math.round(64 * Math.min(1, viewWidth / viewHeight))), height = Math.max(1, Math.round(64 * Math.min(1, viewHeight / viewWidth)));
        const average = { layers: [{ source: color.average, fit: "cover" as const, scale: null, size: null, hide: [], tint: null, bleed: [], pixelSnap: false }], mask: null, opaque: true };
        const { data } = await rasterize(composeSvg(average, { width, height, factor: 1 }, parsed), width, height, true);
        const sums = [0, 0, 0];
        for (let index = 0; index < data.length; index += 1) sums[index % 3]! += data[index]!;
        hex = `#${sums.map(sum => Math.round(sum / (width * height)).toString(16).padStart(2, "0")).join("")}`;
      }
      if (hex.length === 4) hex = `#${[...hex.slice(1)].map(digit => digit + digit).join("")}`;
      colors += `    <color name="${name}">${hex.toUpperCase()}</color>\n`;
    }
    return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by agent-tool images from agent-tool.json. Do not edit. -->\n<resources>\n${colors}</resources>\n`;
  }
  const copy = verbatim(output);
  // Copies pass the same checks as composed sources: no scripts, handlers, or external references.
  if (copy !== null) { sources.parsed([copy]); return sources.text(copy); }
  const parsed = sources.parsed(layerSources(output));
  if (kind === "svg") return composeSvg(output, canvas, parsed, true);
  const pixels = async (width: number, height: number) => rasterize(composeSvg(output, { width, height, factor: canvas.factor }, parsed), width, height, output.opaque);
  if (kind === "ico") return encodeIco(await Promise.all(output.sizes!.map(size => pixels(size, size))));
  return encodePng(await pixels(canvas.width, canvas.height));
}

function select(config: ImagesConfig, names: string[], writable: boolean): [string, ImageTarget][] {
  const available = Object.keys(config.targets);
  if (!available.length) throw new Error("agent-tool.json defines no images.targets.");
  for (const name of names) if (!config.targets[name]) throw new Error(`Unknown image target '${name}'; expected one of: ${available.join(", ")}.`);
  // Without names, build leaves targets that need --out for an explicit request.
  const selected = names.length ? [...new Set(names)] : available.filter(name => !writable || config.targets[name]!.dir !== null);
  if (!selected.length) throw new Error("No image target has a dir; name one and pass --out <directory>.");
  return selected.map(name => [name, config.targets[name]!]);
}

/** Refuses symbolic links below the base, so a committed link cannot redirect a write outside it. */
function assertNoLinks(base: string, destination: string): void {
  let current = base;
  for (const part of path.relative(base, destination).split(path.sep)) {
    current = path.join(current, part);
    let link: boolean;
    try { link = lstatSync(current).isSymbolicLink(); } catch { return; }
    if (link) throw new Error(`Refusing to write through symbolic link ${path.relative(base, current)}.`);
  }
}

/**
 * Replaces a file atomically through an unpredictable, exclusively created
 * temporary name, so no committed link can stand in for it. Sandboxed build
 * phases, such as Xcode's, may write only their declared outputs; there the
 * file is rewritten in place, refusing to follow a link.
 */
export function replaceFile(destination: string, bytes: Uint8Array): void {
  const temporary = `${destination}.${randomUUID()}.tmp`;
  let created = false;
  try {
    writeFileSync(temporary, bytes, { flag: "wx" });
    created = true;
    renameSync(temporary, destination);
  } catch (error) {
    if (created || !["EACCES", "EPERM"].includes((error as NodeJS.ErrnoException).code ?? "")) {
      // Best effort: the original error matters more than a temporary file left behind.
      try { rmSync(temporary, { force: true }); } catch {}
      throw error;
    }
    // Nothing was created, and a sandbox may refuse even an attempt to remove an undeclared path.
    const descriptor = openSync(destination, constants.O_WRONLY | constants.O_CREAT | constants.O_NOFOLLOW);
    try {
      // A hard link would share the file with a path outside the output, so only a sole link is rewritten.
      const stats = fstatSync(descriptor);
      if (!stats.isFile() || stats.nlink !== 1) throw new Error(`Refusing to rewrite ${destination}, which is not a file with a single link.`);
      ftruncateSync(descriptor, 0);
      // writeFileSync on a descriptor repeats short writes until every byte is written.
      writeFileSync(descriptor, bytes);
    } finally { closeSync(descriptor); }
  }
}

function directory(name: string, target: ImageTarget, out: string | undefined): string {
  const dir = out ?? target.dir;
  if (dir === null) throw new Error(`Image target '${name}' has no dir; pass --out <directory>.`);
  return dir;
}

/** Every file each selected target writes, without rendering anything. */
export function listImages(config: ImagesConfig, names: string[]) {
  return {
    sources: SOURCE_DIRECTORY,
    targets: select(config, names, false).map(([name, target]) => ({
      name, dir: target.dir, files: target.outputs.flatMap(output => expand(output).map(file => file.path)),
    })),
  };
}

/**
 * Renders the selected targets under the repository root. Files whose bytes
 * already match are left alone, so native builds see no spurious changes, and
 * the rest are replaced atomically.
 */
export async function buildImages(root: string, config: ImagesConfig, names: string[], out?: string) {
  if (out !== undefined && names.length !== 1) throw new Error("--out needs exactly one image target.");
  const sources = new Sources(root);
  // Render everything first, so a bad source or setting leaves no partial set behind.
  const rendered: { name: string; dir: string; files: { relative: string; destination: string; bytes: Uint8Array }[] }[] = [];
  const owners = new Map<string, string>();
  for (const [name, target] of select(config, names, true)) {
    const dir = directory(name, target, out);
    const files = [];
    for (const output of target.outputs) {
      for (const file of expand(output)) {
        const content = await render(output, { width: file.width, height: file.height, factor: file.factor }, sources);
        const destination = path.resolve(root, dir, file.path);
        // An explicit --out is the caller's choice; configured directories are checked from the repository root.
        assertNoLinks(out === undefined ? root : path.resolve(root, out), destination);
        // Compared without case, as macOS and Windows file systems do.
        const owner = owners.get(destination.toLowerCase());
        if (owner !== undefined) throw new Error(`Image targets '${owner}' and '${name}' both write ${path.relative(root, destination)}.`);
        owners.set(destination.toLowerCase(), name);
        files.push({ relative: path.join(dir, file.path), destination, bytes: typeof content === "string" ? Buffer.from(content) : content });
      }
    }
    rendered.push({ name, dir, files });
  }
  const targets = rendered.map(({ name, dir, files }) => {
    const written: string[] = [], unchanged: string[] = [];
    for (const { relative, destination, bytes } of files) {
      if (existsSync(destination) && Buffer.compare(readFileSync(destination), bytes) === 0) { unchanged.push(relative); continue; }
      mkdirSync(path.dirname(destination), { recursive: true });
      replaceFile(destination, bytes);
      written.push(relative);
    }
    return { name, dir, written, unchanged };
  });
  return { targets };
}
