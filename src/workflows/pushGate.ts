/** The one canonical pre-push body; `push-gate check` requires the tracked hook to match it byte for byte. */
export const PUSH_GATE_HOOK = `#!/bin/sh
# Generated by \`agent-tool push-gate hook\`; \`agent-tool push-gate check\` fails
# when this file differs from it. Declare push checks in agent-tool.json's
# pushGate section instead of editing this file.
set -eu
root=$(git rev-parse --show-toplevel)
cd "$root"
# GUI Git clients can start hooks without mise's shims on PATH.
if command -v bun >/dev/null 2>&1; then
  bun=$(command -v bun)
elif command -v mise >/dev/null 2>&1 && bun=$(mise which bun 2>/dev/null) && [ -x "$bun" ]; then
  :
else
  echo "pre-push: bun is not on PATH and mise cannot provide it. Install the Bun" >&2
  echo "this repository pins (mise install), or put bun on PATH, then push again." >&2
  exit 1
fi
cli="$root/node_modules/@a2f0/agent-tool/src/index.ts"
if [ ! -f "$cli" ]; then
  echo "pre-push: $cli is missing; install this repository's dependencies first." >&2
  exit 1
fi
exec "$bun" "$cli" push-gate run --pre-push "$@"
`;

export type PushScan = "deleted" | "since-remote-tip" | "new-on-remote" | "whole-branch";
/** A pushed ref with the commits the push adds, as exposed to declared steps. */
export interface PushedRef extends PushTuple {
  deleted: boolean;
  scan: PushScan;
  reason: string;
  revisions: string[];
  commits: string[];
  base: string | null;
  range: string | null;
}

/**
 * The push destination as Git names it. `name` is set when the push used a
 * configured remote. `trackingRefs` is true only when that remote fetches from
 * exactly the URL being pushed to, so its tracking refs describe what the
 * destination already has; a separate push URL, or several fetch URLs, do not.
 */
export function pushDestination(remote: string, url: string): { name: string | null; url: string; trackingRefs: boolean } {
  if (!/^[a-zA-Z0-9][a-zA-Z0-9._-]*$/.test(remote)) return { name: null, url, trackingRefs: false };
  const fetchUrls = spawnSync("git", ["remote", "get-url", "--all", remote], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], env: gitEnvironment() });
  if (fetchUrls.status !== 0) return { name: null, url, trackingRefs: false };
  const urls = fetchUrls.stdout.trim().split("\n");
  return { name: remote, url, trackingRefs: urls.length === 1 && urls[0] === url };
}
const isCommit = (value: string) => spawnSync("git", ["cat-file", "-e", `${value}^{commit}`], { stdio: "ignore", env: gitEnvironment() }).status === 0;

/**
 * The commits each pushed ref adds. The remote's old tip is excluded when this
 * clone has it, and so are the tracking refs of a named remote that fetches
 * from the destination. A push to a URL, to a remote whose push URL differs,
 * or over a remote tip this clone never fetched, scans the whole branch instead
 * of subtracting refs that describe another repository: over-scanning is
 * noise, under-scanning lets an unchecked commit through. `base` is the newest
 * commit the destination already has when there is exactly one, else null.
 */
export function pushedRefs(tuples: PushTuple[], remote: string, url: string): PushedRef[] {
  const destination = pushDestination(remote, url);
  const named = destination.trackingRefs;
  const without = destination.name ? `${remote}'s push URL is not the one it fetches from, so its tracking refs do not describe the destination` : "a URL push has no tracking refs to subtract";
  return tuples.map(tuple => {
    if (zeroOid(tuple.localOid)) return { ...tuple, deleted: true, scan: "deleted", reason: "A deletion pushes no commits.", revisions: [], commits: [], base: null, range: null };
    assert(isCommit(tuple.localOid), `${tuple.localRef} (${tuple.localOid}) is not a commit; push-gate checks commits only.`);
    let scan: PushScan, reason: string;
    const excludes: string[] = [];
    let base: string | null = null;
    if (!zeroOid(tuple.remoteOid) && isCommit(tuple.remoteOid)) {
      scan = "since-remote-tip"; base = git(["rev-parse", `${tuple.remoteOid}^{commit}`]);
      excludes.push(tuple.remoteOid);
      if (named) excludes.push(`--remotes=${remote}`);
      reason = named ? `Excludes the remote's old tip and ${remote}'s tracking refs.` : `Excludes the remote's old tip; ${without}.`;
    } else if (!zeroOid(tuple.remoteOid)) {
      scan = "whole-branch"; reason = "The remote's tip is not in this clone, so the whole branch is scanned.";
    } else if (named) {
      scan = "new-on-remote"; excludes.push(`--remotes=${remote}`); reason = `New on the remote; excludes ${remote}'s tracking refs.`;
    } else {
      scan = "whole-branch"; reason = `New on the remote, and ${without}, so the whole branch is scanned.`;
    }
    const revisions = [tuple.localOid, ...(excludes.length ? ["--not", ...excludes] : [])];
    const listed = git(["rev-list", "--boundary", ...revisions, "--"]).split("\n").filter(Boolean);
    const commits = listed.filter(line => !line.startsWith("-"));
    if (!base) {
      const boundary = listed.filter(line => line.startsWith("-")).map(line => line.slice(1));
      const independent = boundary.length > 1 ? git(["merge-base", "--independent", ...boundary]).split("\n").filter(Boolean) : boundary;
      base = independent.length === 1 ? independent[0]! : null;
    }
    return { ...tuple, deleted: false, scan, reason, revisions, commits, base, range: base ? `${base}..${tuple.localOid}` : tuple.localOid };
  });
}

/** Git exports variables such as GIT_DIR to hooks; steps that build fixture repositories must not inherit them. */
export function clearLocalGitEnvironment(): void {
  for (const name of git(["rev-parse", "--local-env-vars"]).split("\n").filter(Boolean)) delete process.env[name];
}

interface Guard { name: string; ref?: string; ok: boolean; durationMs: number; details?: unknown; error?: string }

function guard(guards: Guard[], name: string, ref: string | undefined, check: () => { ok: boolean; details?: unknown }): void {
  const started = performance.now();
  let result: Omit<Guard, "name" | "durationMs">;
  try { const value = check(); result = { ok: value.ok, ...(value.ok || value.details === undefined ? {} : { details: value.details }) }; }
  catch (error) { result = { ok: false, error: (error as Error).message }; }
  guards.push({ name, ...(ref ? { ref } : {}), ...result, durationMs: Math.round(performance.now() - started) });
}

/** The built-in trust guards, from the same implementations as `hooks check`, `skills check`, `permissions check`, `branch check --pre-push`, `commits check`, and `checks binaries`. */
function runGuards(root: string, config: AgentToolConfig, tuples: PushTuple[], remote: string, url: string): { guards: Guard[]; refs: PushedRef[] } {
  const guards: Guard[] = [];
  guard(guards, "hooks", undefined, () => { const result = checkHooks(); return { ok: result.ok, details: { changes: result.changes.filter(change => change.status !== "unchanged"), blockers: result.blockers, configure: result.configure } }; });
  const skills = installedSkillHarnesses(root);
  if (skills) guard(guards, "skills", undefined, () => { const changes = skills.flatMap(harness => checkSkills(root, harness)).filter(change => change.status !== "unchanged"); return { ok: !changes.length, details: { harnesses: skills, changes } }; });
  const permissions = installedPermissionHarness(root);
  if (permissions) guard(guards, "permissions", undefined, () => { const changes = checkPermissions(root, permissions).filter(change => change.status !== "unchanged"); return { ok: !changes.length, details: { harness: permissions, changes } }; });
  guard(guards, "branch", undefined, () => { const branches = pushedBranches(tuples).map(name => ({ name, errors: branchErrors(name, config) })).filter(branch => branch.errors.length); return { ok: !branches.length, details: { branches } }; });
  let refs: PushedRef[] = [];
  guard(guards, "ranges", undefined, () => { refs = pushedRefs(tuples, remote, url); return { ok: true }; });
  for (const ref of refs.filter(item => !item.deleted)) {
    guard(guards, "commits", ref.remoteRef, () => { const findings = commitFindings(ref.commits, config); return { ok: !findings.length, details: { checked: ref.commits.length, findings } }; });
    guard(guards, "binaries", ref.remoteRef, () => { const rejected = rejectedBinaries(binariesAddedByCommits(ref.commits), config); return { ok: !rejected.length, details: { rejected } }; });
  }
  return { guards, refs };
}

function worktreeState(refs: PushedRef[]): { headOid: string; matchesPush: boolean; differences: string[] } {
  const headOid = git(["rev-parse", "HEAD"]);
  const differences: string[] = [];
  for (const ref of refs.filter(item => !item.deleted)) {
    const commit = git(["rev-parse", `${ref.localOid}^{commit}`]);
    if (commit !== headOid) differences.push(`${ref.remoteRef} receives ${commit}, but HEAD is ${headOid}.`);
  }
  if (git(["status", "--porcelain=v1", "--untracked-files=normal"])) differences.push("The working tree has uncommitted or untracked changes.");
  return { headOid, matchesPush: !differences.length, differences };
}

const seconds = (ms: number) => `${(ms / 1000).toFixed(1)}s`;
const say = (message: string) => writeSync(2, `push-gate: ${message}\n`);

export async function runPushGate(args: string[], root: string): Promise<number> {
  assert(args.length === 3 && args[0] === "--pre-push" && !!args[1] && !!args[2], "Usage: push-gate run --pre-push <remote> <url>");
  const [, remote, url] = args as [string, string, string];
  const started = performance.now();
  assert(!isatty(0), "push-gate run reads the refs being pushed from stdin; run it through git push.");
  const tuples = parsePrePushInput(readFileSync(0, "utf8"));
  const config = loadConfig(root);
  const gate = config.pushGate;
  const notes: string[] = [];
  if (!gate) notes.push("agent-tool.json declares no pushGate section; only the built-in guards ran.");
  const remoteInfo = pushDestination(remote, url);
  const { guards, refs } = runGuards(root, config, tuples, remote, url);
  const failed = guards.filter(item => !item.ok);
  for (const item of failed) {
    const detail = item.error ?? JSON.stringify(item.details);
    say(`${item.name}${item.ref ? ` (${item.ref})` : ""} failed: ${detail.length > 600 ? `${detail.slice(0, 600)}… (see the JSON report)` : detail}`);
  }
  const budgetSeconds = gate?.budgetSeconds ?? PUSH_GATE_BUDGET_SECONDS;
  const summary = (group: { record: GroupRecord; report: string } | null, worktree: ReturnType<typeof worktreeState> | null) => {
    const elapsedMs = Math.round(performance.now() - started);
    const steps = group?.record.steps.map(step => ({ label: step.label, status: step.status, durationMs: step.receipt?.durationMs ?? null, log: step.receipt?.log ?? null })) ?? [];
    const slowest = steps.filter(step => step.durationMs !== null).sort((a, b) => b.durationMs! - a.durationMs!).slice(0, 3).map(step => ({ label: step.label, durationMs: step.durationMs! }));
    const exceeded = elapsedMs > budgetSeconds * 1000;
    const guardMs = guards.reduce((sum, item) => sum + item.durationMs, 0);
    const warnings: string[] = [];
    if (exceeded) warnings.push(`The push gate took ${seconds(elapsedMs)}, over its ${budgetSeconds}s budget (pushGate.budgetSeconds). ${slowest.length ? `Slowest steps: ${slowest.map(step => `${step.label} ${seconds(step.durationMs)}`).join(", ")}. Move them to CI.` : `The built-in guards took ${seconds(guardMs)}.`}`);
    if (worktree && !worktree.matchesPush) warnings.push(`The declared steps checked the working tree, which is not what this push sends (${worktree.differences.join(" ")}) CI checks the pushed commits and is the authority.`);
    for (const warning of warnings) say(warning);
    const ok = !failed.length && (!group || group.record.status === "passed");
    output({
      ok, remote: remoteInfo,
      refs: refs.map(({ commits, ...ref }) => ({ ...ref, commits: commits.length })),
      guards, steps: group ? { report: group.report, status: group.record.status, durationMs: group.record.durationMs, error: group.record.error, steps } : null,
      worktree, budget: { seconds: budgetSeconds, elapsedMs, exceeded, slowest }, notes, warnings,
    });
  };
  if (failed.length) { summary(null, null); return 1; }
  const steps = gate?.steps ?? [];
  if (!steps.length || refs.every(ref => ref.deleted)) {
    if (steps.length) notes.push(refs.length ? "This push only deletes refs; the declared steps did not run." : "Git passed no refs to push; the declared steps did not run.");
    summary(null, null); return 0;
  }
  const worktree = worktreeState(refs);
  const directory = mkdtempSync(path.join(tmpdir(), "agent-tool-push-gate-"));
  let result: Awaited<ReturnType<typeof executeGroup>>;
  try {
    const context = path.join(directory, "push.json");
    writeFileSync(context, `${JSON.stringify({ schemaVersion: 1, remote: remoteInfo, headOid: worktree.headOid, worktreeMatchesPush: worktree.matchesPush, refs }, null, 2)}\n`, { mode: 0o600, flag: "wx" });
    process.env[PUSH_GATE_ENV] = context;
    say(`running ${steps.length} declared step(s): ${steps.map(step => step.label).join(", ")}`);
    result = await executeGroup({ label: "push-gate", steps: steps.map(({ label, command }) => ({ label, command })) }, (record, report) => summary({ record, report }, worktree));
  } finally {
    // Removed before any signal is re-raised, which ends the process.
    delete process.env[PUSH_GATE_ENV];
    rmSync(directory, { recursive: true, force: true });
  }
  return reraiseGroupSignal(result);
}

export interface PushGateCheck {
  ok: boolean;
  hook: { path: string; tracked: boolean; canonical: boolean | null; installed: boolean };
  pushGate: { declared: boolean; budgetSeconds: number | null };
  steps: { label: string; command: string[]; allowSlow: string | null; ok: boolean; findings: StepFinding[]; errors: string[] }[];
  errors: string[];
  notes: string[];
}

/** Read-only: the tracked hook is the canonical body, hooks.files installs it, and no step runs tests or installs unless it says why. */
export function checkPushGate(root: string, config: AgentToolConfig): PushGateCheck {
  const errors: string[] = [], notes: string[] = [];
  const tracked = spawnSync("git", ["ls-files", "--error-unmatch", "--", PRE_PUSH_SOURCE], { cwd: root, stdio: "ignore", env: gitEnvironment() }).status === 0;
  const file = path.join(root, PRE_PUSH_SOURCE);
  const canonical = tracked && existsSync(file) ? readFileSync(file, "utf8") === PUSH_GATE_HOOK : tracked ? false : null;
  const installed = config.hooks.files.some(entry => entry.source === PRE_PUSH_SOURCE && entry.target === "pre-push" && entry.executable);
  const gate = config.pushGate;
  if (!gate && !tracked) {
    notes.push(`No push gate: agent-tool.json has no pushGate section and ${PRE_PUSH_SOURCE} is not tracked.`);
    return { ok: true, hook: { path: PRE_PUSH_SOURCE, tracked, canonical, installed }, pushGate: { declared: false, budgetSeconds: null }, steps: [], errors, notes };
  }
  if (!gate) errors.push(`${PRE_PUSH_SOURCE} is tracked, but agent-tool.json declares no pushGate section; declare one, even with no steps.`);
  if (!tracked) errors.push(`pushGate is declared, but ${PRE_PUSH_SOURCE} is not tracked; commit the output of \`agent-tool push-gate hook\` there.`);
  else if (!canonical) errors.push(`${PRE_PUSH_SOURCE} differs from \`agent-tool push-gate hook\`; replace it with that output byte for byte.`);
  if (!installed) errors.push(`hooks.files does not install ${PRE_PUSH_SOURCE} as an executable pre-push: add { "source": "${PRE_PUSH_SOURCE}", "target": "pre-push", "executable": true }.`);
  const steps = (gate?.steps ?? []).map(step => {
    const { findings, errors: stepErrors } = resolveStep(root, step.command);
    const ok = !stepErrors.length && (!findings.length || !!step.allowSlow);
    for (const finding of step.allowSlow ? [] : findings) errors.push(`Step '${step.label}' runs ${finding.kind === "test" ? "a test run" : "a dependency install"} (${finding.runner}): ${finding.chain.join(" -> ")}. Move it to CI, or give the step an allowSlow reason.`);
    for (const error of stepErrors) errors.push(`Step '${step.label}': ${error}`);
    return { label: step.label, command: step.command, allowSlow: step.allowSlow ?? null, ok, findings, errors: stepErrors };
  });
  return { ok: !errors.length, hook: { path: PRE_PUSH_SOURCE, tracked, canonical, installed }, pushGate: { declared: !!gate, budgetSeconds: gate?.budgetSeconds ?? null }, steps, errors, notes };
}

/** `push-gate hook` needs no repository; `run` resolves the root before clearing Git's hook environment. */
export async function pushGateCommand(args: string[]): Promise<number> {
  const action = args.shift();
  if (action === "hook") { assert(!args.length, "Usage: push-gate hook"); writeSync(1, PUSH_GATE_HOOK); return 0; }
  if (action === "check") {
    assert(!args.length, "Usage: push-gate check");
    const root = checkoutRoot(); process.chdir(root);
    const result = checkPushGate(root, loadConfig(root));
    output(result); return result.ok ? 0 : 1;
  }
  assert(action === "run", "Usage: push-gate hook | check | run --pre-push <remote> <url>");
  const root = checkoutRoot(); process.chdir(root);
  clearLocalGitEnvironment();
  assert(realpathSync(checkoutRoot()) === realpathSync(root), `Without Git's hook environment the repository resolves elsewhere than ${root}; run push-gate from the checkout.`);
  return runPushGate(args, root);
}
