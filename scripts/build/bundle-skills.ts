import { existsSync, lstatSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dir, "../..");
const bundled: Record<string, string> = {};
const references: Record<string, Record<string, string>> = {};
for (const name of readdirSync(path.join(root, "skills")).sort()) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) throw new Error(`Invalid skill directory '${name}'.`);
  const source = readFileSync(path.join(root, "skills", name, "SKILL.md"), "utf8");
  if (!source.startsWith(`---\nname: ${name}\n`) || !source.includes("\ndescription: ")) throw new Error(`Invalid skill frontmatter for '${name}'.`);
  if (!/\n---\n\n# [^\n]+\n\n/.test(source)) throw new Error(`Missing top-level Markdown heading for skill '${name}'.`);
  bundled[name] = source;
  // Markdown files directly under references/ ship with the skill; other files stay in the repository.
  const directory = path.join(root, "skills", name, "references");
  if (!existsSync(directory)) continue;
  if (!lstatSync(directory).isDirectory()) throw new Error(`Skill references must be a directory: skills/${name}/references`);
  for (const file of readdirSync(directory).sort()) {
    if (!file.endsWith(".md")) continue;
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*\.md$/.test(file)) throw new Error(`Invalid skill reference name 'skills/${name}/references/${file}'.`);
    if (!lstatSync(path.join(directory, file)).isFile()) throw new Error(`Skill reference is not a regular file: skills/${name}/references/${file}`);
    (references[name] ??= {})[`references/${file}`] = readFileSync(path.join(directory, file), "utf8");
  }
}
writeFileSync(
  path.join(root, "src/skills/bundled.ts"),
  `// Generated by scripts/build/bundle-skills.ts; edit skills/*/SKILL.md and skills/*/references/*.md.
export const BUNDLED_SKILLS: Readonly<Record<string, string>> = ${JSON.stringify(bundled, null, 2)};
/** Markdown files a skill ships beside its SKILL.md, by skill and then by path within the skill directory. */
export const BUNDLED_SKILL_REFERENCES: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(references, null, 2)};
`,
);
